import { http } from './http'

const basePath: Record<string,string> = { CENTOS:'centos', ROS:'ros', LINE:'lines', IP:'ips' }
export const resourceApi = {
  overview: () => http.get('/resources/overview'),
  options: () => http.get('/resources/options'),
  baseList: (type:string, params:any) => http.get(`/resources/${basePath[type]}`, { params }),
  baseDetail: (type:string, id:number) => http.get(`/resources/${basePath[type]}/${id}`),
  syncBase: (type:string, reason:string) => http.post(`/resources/${basePath[type]}/sync`, { reason }),
  pools: (params:any) => http.get('/resource-pools',{params}),
  pool: (id:number) => http.get(`/resource-pools/${id}`),
  poolIps: (id:number,params:any) => http.get(`/resource-pools/${id}/ips`,{params}),
  createPool: (data:any) => http.post('/resource-pools',data),
  updatePool: (id:number,data:any) => http.put(`/resource-pools/${id}`,data),
  enablePool: (id:number,reason:string) => http.post(`/resource-pools/${id}/enable`,{reason}),
  disablePool: (id:number,reason:string) => http.post(`/resource-pools/${id}/disable`,{reason}),
  recalcPool: (id:number,reason:string) => http.post(`/resource-pools/${id}/recalculate`,{reason}),
  exclusive: (params:any) => http.get('/exclusive-allocations',{params}),
  exclusiveDetail: (id:number) => http.get(`/exclusive-allocations/${id}`),
  releaseExclusive: (id:number,reason:string) => http.post(`/exclusive-allocations/${id}/release`,{reason}),
  domains: (params:any) => http.get('/domains',{params}),
  domain: (id:number) => http.get(`/domains/${id}`),
  createDomain: (data:any) => http.post('/domains',data),
  updateDomain: (id:number,data:any) => http.put(`/domains/${id}`,data),
  refreshDomain: (id:number,reason:string) => http.post(`/domains/${id}/refresh`,{reason}),
  suppliers: (params:any) => http.get('/suppliers',{params}),
  supplier: (id:number) => http.get(`/suppliers/${id}`),
  createSupplier: (data:any) => http.post('/suppliers',data),
  updateSupplier: (id:number,data:any) => http.put(`/suppliers/${id}`,data),
  testSupplier: (id:number,reason:string) => http.post(`/suppliers/${id}/test`,{reason}),
  enableSupplier: (id:number,reason:string) => http.post(`/suppliers/${id}/enable`,{reason}),
  pauseSupplier: (id:number,reason:string) => http.post(`/suppliers/${id}/pause`,{reason}),
  disableSupplier: (id:number,reason:string) => http.post(`/suppliers/${id}/disable`,{reason}),
  syncTasks: (params:any) => http.get('/sync-tasks',{params}),
  syncTask: (id:number) => http.get(`/sync-tasks/${id}`),
  syncDetails: (id:number) => http.get(`/sync-tasks/${id}/details`),
  createSync: (data:any) => http.post('/sync-tasks',data),
  retrySync: (id:number,reason:string) => http.post(`/sync-tasks/${id}/retry`,{reason})
}
