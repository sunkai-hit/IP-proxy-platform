CREATE TABLE alarm_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code VARCHAR(64) NOT NULL,
    rule_name VARCHAR(200) NOT NULL,
    object_type VARCHAR(32) NOT NULL CHECK (object_type IN ('CENTOS','ROS','LINE','IP','POOL','SUPPLIER','SERVICE')),
    metric_code VARCHAR(64) NOT NULL,
    operator VARCHAR(16) NOT NULL CHECK (operator IN ('EQ','NE','GT','GTE','LT','LTE','IN','NOT_IN')),
    threshold JSONB NOT NULL,
    duration_seconds INT NOT NULL DEFAULT 0,
    consecutive_count INT NOT NULL DEFAULT 1 CHECK (consecutive_count > 0),
    severity VARCHAR(20) NOT NULL CHECK (severity IN ('INFO','MINOR','MAJOR','CRITICAL')),
    notification_channels JSONB NOT NULL DEFAULT '["PLATFORM"]'::jsonb,
    notify_recovery BOOLEAN NOT NULL DEFAULT TRUE,
    repeat_interval_seconds INT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by BIGINT,
    version INT NOT NULL DEFAULT 0, deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uk_alarm_rule_code ON alarm_rule(rule_code) WHERE deleted = FALSE;
CREATE INDEX idx_alarm_rule_object_status ON alarm_rule(object_type, status) WHERE deleted = FALSE;

CREATE TABLE alarm_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_no VARCHAR(64) NOT NULL,
    rule_id BIGINT REFERENCES alarm_rule(id),
    object_type VARCHAR(32) NOT NULL,
    object_id BIGINT NOT NULL,
    object_name VARCHAR(255),
    severity VARCHAR(20) NOT NULL CHECK (severity IN ('INFO','MINOR','MAJOR','CRITICAL')),
    metric_code VARCHAR(64),
    threshold JSONB,
    current_value JSONB,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACKNOWLEDGED','PROCESSING','RECOVERED','CLOSED')),
    first_triggered_at TIMESTAMPTZ NOT NULL,
    last_triggered_at TIMESTAMPTZ NOT NULL,
    occurrence_count INT NOT NULL DEFAULT 1,
    acknowledged_by BIGINT REFERENCES sys_user(id),
    acknowledged_at TIMESTAMPTZ,
    handler_id BIGINT REFERENCES sys_user(id),
    recovered_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    recovery_value JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version INT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uk_alarm_event_no ON alarm_event(alarm_no);
CREATE INDEX idx_alarm_event_status_severity ON alarm_event(status, severity, first_triggered_at DESC);
CREATE INDEX idx_alarm_event_object ON alarm_event(object_type, object_id, status);
CREATE INDEX idx_alarm_event_rule ON alarm_event(rule_id, first_triggered_at DESC);

CREATE TABLE alarm_process_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id BIGINT NOT NULL REFERENCES alarm_event(id) ON DELETE CASCADE,
    action VARCHAR(32) NOT NULL CHECK (action IN ('ACKNOWLEDGE','START_PROCESS','ADD_NOTE','RECOVER','CLOSE','REOPEN')),
    before_status VARCHAR(20),
    after_status VARCHAR(20),
    operator_id BIGINT REFERENCES sys_user(id),
    remark VARCHAR(2000),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_alarm_process_alarm_time ON alarm_process_record(alarm_id, occurred_at DESC);

CREATE TABLE alarm_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alarm_id BIGINT NOT NULL REFERENCES alarm_event(id) ON DELETE CASCADE,
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('PLATFORM','DINGTALK','WEBHOOK')),
    target VARCHAR(1000),
    template_code VARCHAR(64),
    message_snapshot TEXT,
    result VARCHAR(20) NOT NULL CHECK (result IN ('PENDING','SUCCESS','FAILURE')),
    retry_count INT NOT NULL DEFAULT 0,
    sent_at TIMESTAMPTZ,
    error_message VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_alarm_notification_alarm ON alarm_notification(alarm_id, created_at DESC);
CREATE INDEX idx_alarm_notification_result ON alarm_notification(result, created_at);

