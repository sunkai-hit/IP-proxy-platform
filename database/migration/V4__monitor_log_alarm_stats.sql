-- IP代理管理平台 V4 - 监控、日志、告警、统计

CREATE TABLE mon_object_status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_type VARCHAR(32) NOT NULL CHECK (object_type IN ('CENTOS','ROS','LINE','IP','POOL','SUPPLIER','SERVICE')),
    object_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' CHECK (status IN ('NORMAL','ABNORMAL','ONLINE','OFFLINE','UNKNOWN')),
    health_score NUMERIC(6,2),
    current_metrics JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_success_at TIMESTAMPTZ,
    last_failure_at TIMESTAMPTZ,
    last_collected_at TIMESTAMPTZ,
    last_error VARCHAR(1000),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version INT NOT NULL DEFAULT 0,
    UNIQUE(object_type, object_id)
);
CREATE INDEX idx_mon_object_status_state ON mon_object_status(object_type, status);
CREATE INDEX idx_mon_object_status_collected ON mon_object_status(last_collected_at);

CREATE TABLE mon_metric_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    object_type VARCHAR(32) NOT NULL,
    object_id BIGINT NOT NULL,
    metric_code VARCHAR(64) NOT NULL,
    metric_value NUMERIC(24,6),
    metric_text VARCHAR(500),
    labels JSONB NOT NULL DEFAULT '{}'::jsonb,
    collected_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (id, collected_at)
) PARTITION BY RANGE (collected_at);
CREATE INDEX idx_mon_metric_object_time ON mon_metric_sample(object_type, object_id, collected_at DESC);
CREATE INDEX idx_mon_metric_code_time ON mon_metric_sample(metric_code, collected_at DESC);
CREATE TABLE mon_metric_sample_default PARTITION OF mon_metric_sample DEFAULT;

CREATE TABLE log_ip_extract (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id VARCHAR(64) NOT NULL,
    customer_id BIGINT REFERENCES customer(id),
    account_id BIGINT REFERENCES customer_account(id),
    service_id BIGINT REFERENCES svc_instance(id),
    product_id BIGINT REFERENCES prd_product(id),
    client_ip INET,
    requested_protocol_code VARCHAR(64),
    region_code VARCHAR(64),
    carrier_code VARCHAR(64),
    requested_count INT NOT NULL DEFAULT 0,
    returned_count INT NOT NULL DEFAULT 0,
    returned_ips JSONB NOT NULL DEFAULT '[]'::jsonb,
    resource_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
    result VARCHAR(20) NOT NULL CHECK (result IN ('SUCCESS','FAILURE','PARTIAL')),
    error_code VARCHAR(64),
    error_message VARCHAR(1000),
    elapsed_ms INT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id, occurred_at)
) PARTITION BY RANGE (occurred_at);
CREATE INDEX idx_log_ip_extract_service_time ON log_ip_extract(service_id, occurred_at DESC);
CREATE INDEX idx_log_ip_extract_customer_time ON log_ip_extract(customer_id, occurred_at DESC);
CREATE INDEX idx_log_ip_extract_request ON log_ip_extract(request_id, occurred_at DESC);
CREATE TABLE log_ip_extract_default PARTITION OF log_ip_extract DEFAULT;

