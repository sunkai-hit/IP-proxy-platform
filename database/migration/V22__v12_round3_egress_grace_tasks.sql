-- 唯一事实源：每个对外固定IPv4的一次服务授权，SHARED、EXCLUSIVE不能并发违反排他承诺。
-- 过渡期不允许相同IPv4的重复独享记录，即使同客户；同客户复用属于待业务确认事项。
CREATE TABLE IF NOT EXISTS svc_egress_claim (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES svc_instance(id),
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  source_line_id BIGINT REFERENCES res_line(id),
  egress_ipv4 INET NOT NULL,
  claim_mode VARCHAR(16) NOT NULL CHECK (claim_mode IN ('SHARED','EXCLUSIVE')),
  claim_status VARCHAR(24) NOT NULL DEFAULT 'RESERVED' CHECK (claim_status IN ('RESERVED','ACTIVE','GRACE_HELD','RELEASE_PENDING','RELEASED')),
  acquired_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  hold_until_at TIMESTAMPTZ,
  released_at TIMESTAMPTZ,
  verified_at TIMESTAMPTZ,
  operation_key VARCHAR(128),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (family(egress_ipv4)=4),
  CHECK (claim_status<>'RELEASED' OR released_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_svc_egress_ipv4 ON svc_egress_claim(egress_ipv4,claim_status);
CREATE INDEX IF NOT EXISTS idx_svc_egress_service ON svc_egress_claim(service_id,claim_status);
CREATE UNIQUE INDEX IF NOT EXISTS ux_svc_single_active_exclusive_ipv4 ON svc_egress_claim(egress_ipv4)
 WHERE claim_mode='EXCLUSIVE' AND claim_status IN ('RESERVED','ACTIVE','GRACE_HELD','RELEASE_PENDING');

CREATE OR REPLACE FUNCTION fn_validate_svc_egress_claim() RETURNS TRIGGER AS $$
DECLARE real_customer BIGINT; real_type VARCHAR(20);
BEGIN
  SELECT customer_id,product_type INTO real_customer,real_type FROM svc_instance WHERE id=NEW.service_id AND deleted=FALSE;
  IF real_customer IS NULL OR real_customer<>NEW.customer_id THEN
     RAISE EXCEPTION 'EGRESS_SERVICE_CUSTOMER_MISMATCH' USING ERRCODE='23514';
  END IF;
  IF NEW.claim_mode='EXCLUSIVE' AND real_type<>'EXCLUSIVE_IP' THEN
     RAISE EXCEPTION 'EGRESS_MODE_MISMATCH' USING ERRCODE='23514';
  END IF;
  IF NEW.claim_status IN ('RESERVED','ACTIVE','GRACE_HELD','RELEASE_PENDING') THEN
    PERFORM pg_advisory_xact_lock(hashtext(host(NEW.egress_ipv4))::bigint);
    IF EXISTS (
      SELECT 1 FROM svc_egress_claim c
      WHERE c.id<>COALESCE(NEW.id,-1) AND c.egress_ipv4=NEW.egress_ipv4
        AND c.claim_status IN ('RESERVED','ACTIVE','GRACE_HELD','RELEASE_PENDING')
        AND (NEW.claim_mode='EXCLUSIVE' OR c.claim_mode='EXCLUSIVE')
    ) THEN RAISE EXCEPTION 'EGRESS_IPV4_EXCLUSIVE_CONFLICT' USING ERRCODE='23505'; END IF;
  END IF;
  NEW.updated_at=now();
  RETURN NEW;
END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_validate_svc_egress_claim ON svc_egress_claim;
CREATE TRIGGER trg_validate_svc_egress_claim BEFORE INSERT OR UPDATE OF egress_ipv4,claim_mode,claim_status,customer_id,service_id
  ON svc_egress_claim FOR EACH ROW EXECUTE FUNCTION fn_validate_svc_egress_claim();

CREATE TABLE IF NOT EXISTS svc_backup_candidate (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES svc_instance(id),
  line_id BIGINT NOT NULL REFERENCES res_line(id),
  expected_ipv4 INET,
  candidate_status VARCHAR(20) NOT NULL DEFAULT 'CANDIDATE' CHECK (candidate_status IN ('CANDIDATE','INELIGIBLE','DISABLED')),
  health_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
  last_checked_at TIMESTAMPTZ,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(service_id,line_id),
  CHECK (expected_ipv4 IS NULL OR family(expected_ipv4)=4)
);
CREATE INDEX IF NOT EXISTS idx_svc_backup_candidate_service ON svc_backup_candidate(service_id,candidate_status);

CREATE TABLE IF NOT EXISTS svc_action_task (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_key VARCHAR(128) NOT NULL UNIQUE,
  service_id BIGINT NOT NULL REFERENCES svc_instance(id),
  action_type VARCHAR(32) NOT NULL CHECK (action_type IN ('PROVISION','STOP_FOR_GRACE','RENEW_RESTORE','MANUAL_FAILOVER','TERMINATE','RELEASE','EXTERNAL_PROXY_UNBIND')),
  task_status VARCHAR(24) NOT NULL DEFAULT 'PENDING' CHECK (task_status IN ('PENDING','PRECHECK_BLOCKED','RUNNING','VERIFYING','SUCCEEDED','FAILED','COMPENSATION_REQUIRED')),
  stage VARCHAR(40) NOT NULL DEFAULT 'PENDING',
  actor_user_id BIGINT,
  reason VARCHAR(1000),
  request_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
  result_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
  remote_operation_id VARCHAR(128),
  last_error_code VARCHAR(80),
  last_error_message VARCHAR(1000),
  attempt_count INT NOT NULL DEFAULT 0 CHECK (attempt_count>=0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_svc_action_task_service ON svc_action_task(service_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_svc_action_task_status ON svc_action_task(task_status,updated_at);
COMMENT ON TABLE svc_action_task IS '任务记录不替代真实数据面回执；SUCCEEDED必须依产品及资源真实验证结果';
