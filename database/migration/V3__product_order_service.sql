CREATE TABLE svc_resource_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES svc_instance(id) ON DELETE CASCADE,
    resource_type VARCHAR(20) NOT NULL CHECK (resource_type IN ('POOL','CENTOS','ROS','LINE','IP','DOMAIN','SUPPLIER')),
    resource_id BIGINT NOT NULL,
    binding_role VARCHAR(20) NOT NULL DEFAULT 'PRIMARY' CHECK (binding_role IN ('PRIMARY','BACKUP','CANDIDATE','ENTRY','OUTBOUND')),
    effective_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','RELEASED','FAILED')),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    UNIQUE(service_id, resource_type, resource_id, effective_at)
);
CREATE INDEX idx_svc_resource_binding_service ON svc_resource_binding(service_id, status);
CREATE INDEX idx_svc_resource_binding_resource ON svc_resource_binding(resource_type, resource_id, status);

CREATE TABLE svc_credential (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES svc_instance(id) ON DELETE CASCADE,
    credential_type VARCHAR(32) NOT NULL CHECK (credential_type IN ('TOKEN','USERNAME_PASSWORD','VPN_PRIVATE_KEY','VPN_CERTIFICATE','TUNNEL_ACCOUNT')),
    account_name VARCHAR(128),
    secret_hash VARCHAR(255),
    secret_cipher TEXT,
    secret_mask VARCHAR(128),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','FROZEN','REVOKED','EXPIRED')),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expire_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    rotated_at TIMESTAMPTZ,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by BIGINT,
    version INT NOT NULL DEFAULT 0, deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_svc_credential_service ON svc_credential(service_id, credential_type, status) WHERE deleted = FALSE;
CREATE INDEX idx_svc_credential_account ON svc_credential(account_name) WHERE deleted = FALSE AND account_name IS NOT NULL;

CREATE TABLE svc_whitelist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES svc_instance(id) ON DELETE CASCADE,
    ip_address INET NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DISABLED')),
    remark VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by BIGINT,
    version INT NOT NULL DEFAULT 0, deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uk_svc_whitelist_service_ip ON svc_whitelist(service_id, ip_address) WHERE deleted = FALSE;

CREATE TABLE svc_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_no VARCHAR(64) NOT NULL,
    service_id BIGINT NOT NULL REFERENCES svc_instance(id),
    change_type VARCHAR(32) NOT NULL CHECK (change_type IN ('RENEW','EXPAND','PACKAGE_CHANGE','IP_CHANGE','LINE_CHANGE','POOL_CHANGE','SUSPEND','RESUME','TERMINATE','CREDENTIAL_RESET')),
    before_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    after_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    reason VARCHAR(1000),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','SUCCESS','FAILED','CANCELLED')),
    operator_id BIGINT REFERENCES sys_user(id),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    error_message VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by BIGINT,
    version INT NOT NULL DEFAULT 0, deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uk_svc_change_no ON svc_change(change_no) WHERE deleted = FALSE;
CREATE INDEX idx_svc_change_service_time ON svc_change(service_id, created_at DESC) WHERE deleted = FALSE;
CREATE INDEX idx_svc_change_status ON svc_change(status, created_at DESC) WHERE deleted = FALSE;

CREATE TABLE svc_release_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_no VARCHAR(64) NOT NULL,
    service_id BIGINT NOT NULL REFERENCES svc_instance(id),
    trigger_type VARCHAR(20) NOT NULL CHECK (trigger_type IN ('EXPIRE','TERMINATE','MANUAL','CHANGE')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','SUCCESS','PARTIAL_SUCCESS','FAILED')),
    credential_result JSONB NOT NULL DEFAULT '{}'::jsonb,
    resource_result JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    operator_id BIGINT REFERENCES sys_user(id),
    error_message VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_svc_release_no ON svc_release_record(release_no);
CREATE INDEX idx_svc_release_service_time ON svc_release_record(service_id, created_at DESC);
CREATE INDEX idx_svc_release_status ON svc_release_record(status, created_at DESC);
